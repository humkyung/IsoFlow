// Shape3D.java — 프론트가 만들 3D 지오메트리 종류. 엔진이 결정해 내려보낸다
package co.atools.isoflow.engine.scene;

/**
 * 형상 결정을 <b>엔진 한 곳</b>에 둔다.
 * 프론트가 컴포넌트 타입에서 다시 추론하면 새 타입을 지원할 때 규칙이 두 곳으로 갈라진다.
 */
public enum Shape3D {
    /** 두 END 를 잇는 원기둥 */
    PIPE,
    /**
     * 두 END 를 잇는 원환 조각.
     * <b>CENTRE-POINT 는 호의 중심이 아니라 두 배관 축이 만나는 모서리점</b>이다 —
     * 호의 중심은 프론트가 거기서 파생해 계산한다.
     */
    ELBOW,
    /** 런(END↔END) + 분기(CENTRE→BRANCH1) */
    TEE,
    /** 런 + 분기 2개 */
    CROSS,
    /** CENTRE(모재)→BRANCH1(분기) 스터브 */
    OLET,
    /**
     * 두 END 사이의 원뿔대 — 양 끝 반지름이 다르다.
     * {@code flatDirection} 이 함께 오면 편심 리듀서다(한쪽 모선이 평평).
     */
    REDUCER,
    /** 밸브/플랜지/커플링 등 두 END 사이의 굵은 원기둥 */
    BODY,
    /**
     * 앵글 밸브 — 두 END 에서 굵고 <b>CENTRE(모서리)로 좁아지는</b> 원뿔 2개.
     * 두 END 는 90° 로 꺾여 있어 직선으로 이으면 모서리를 가로지른다.
     */
    VALVE_ANGLE,
    /**
     * 버터플라이 밸브 — 납작한 웨이퍼 몸통 + {@code spindleDirection} 방향 스템 + 기어박스 + 핸드휠.
     * 스템 방향을 모르면 몸통만 남으므로 엔진이 {@link #BODY} 로 낮춘다.
     */
    VALVE_BUTTERFLY,
    /**
     * 게이트 밸브 — 보타이 몸통(END 에서 굵고 CENTRE 로 좁아진다) + 보닛 + 라이징 스템 + 핸드휠.
     * 조작부는 {@code spindleDirection} 이 있을 때만 붙고, 없으면 몸통만 남는다.
     */
    VALVE_GATE,
    /**
     * 글로브 밸브 — 게이트와 같은 보타이 몸통에 <b>가운데 구(球)</b>가 하나 더 붙는다.
     * 2D 심볼도 같은 규칙이다(게이트=보타이, 글로브=보타이+채운 원). 조작부는 게이트와 같다.
     */
    VALVE_GLOBE,
    /**
     * 볼 밸브 — 보타이 몸통 + 가운데 구 + <b>레버</b>.
     * 90° 회전이라 실물에서도 핸드휠이 아니라 레버가 달린다. 3D 에는 2D 의 채움/윤곽 구분이 없어
     * 구 크기만으로는 글로브와 구별되지 않으므로, 조작부로 구분한다.
     */
    VALVE_BALL,
    /**
     * 체크 밸브(스윙형) — <b>배럴 몸통 + 볼트 보닛(캡)</b>. 스템·핸드휠이 없다.
     * {@code flowToEnd} 를 알면 캡이 상류(힌지) 쪽으로 밀리고, 몰라도 형상 자체는 성립한다.
     */
    VALVE_CHECK,
    /**
     * 플러그 밸브 — 보타이 몸통 + <b>스핀들 축 방향 테이퍼 플러그</b> + 레버.
     * 볼과 같은 90° 회전이라 조작부는 같고, 가운데가 구가 아니라 테이퍼 원기둥인 점만 다르다
     * (2D 도 볼=원 / 플러그=사각형 으로 같은 자리에서 가른다).
     */
    VALVE_PLUG,
    /** 3D 에 그리지 않음 (용접·유동화살표·종단 표시) */
    NONE
}
